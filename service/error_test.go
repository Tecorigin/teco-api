func TestRelayErrorHandlerCapturesBodyRequestID(t *testing.T) {
	for _, testCase := range []struct {
		name           string
		body           string
		headerID       string
		expectedID     string
		expectedSource string
	}{
		{"top-level request id", `{"request_id":" req-400 ","error":{"message":"invalid request"}}`, "", "req-400", "body:request_id"},
		{"top-level trace id", `{"trace_id":"trace-400","error":{"message":"invalid request"}}`, "", "trace-400", "body:trace_id"},
		{"nested request id", `{"error":{"request_id":"nested-400","message":"invalid request"}}`, "", "nested-400", "body:request_id"},
		{"nested trace id", `{"error":{"trace_id":"nested-trace","message":"invalid request"}}`, "", "nested-trace", "body:trace_id"},
		{"header takes precedence", `{"request_id":"body-id","error":{"message":"invalid request"}}`, "header-id", "header-id", "header:x-request-id"},
		{"no id", `{"error":{"message":"invalid request"}}`, "", "", ""},
		{"invalid id type", `{"request_id":123,"error":{"message":"invalid request"}}`, "", "", ""},
	} {
		t.Run(testCase.name, func(t *testing.T) {
			ctx, _ := gin.CreateTestContext(httptest.NewRecorder())
			if testCase.headerID != "" {
				ctx.Set(common.UpstreamRequestIdKey, testCase.headerID)
				ctx.Set("upstream_request_id", testCase.headerID)
				ctx.Set("upstream_request_id_source", "header:x-request-id")
			}
			resp := &http.Response{
				StatusCode: http.StatusBadRequest,
				Body:       io.NopCloser(strings.NewReader(testCase.body)),
			}

			apiErr := RelayErrorHandler(ctx, resp, false)

			require.NotNil(t, apiErr)
			assert.Equal(t, http.StatusBadRequest, apiErr.StatusCode)
			assert.Equal(t, "invalid request", apiErr.Error())
			assert.Equal(t, testCase.expectedID, ctx.GetString(common.UpstreamRequestIdKey))
			assert.Equal(t, testCase.expectedID, ctx.GetString("upstream_request_id"))
			assert.Equal(t, testCase.expectedSource, ctx.GetString("upstream_request_id_source"))
		})
	}
}

func TestResetStatusCode(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name             string
		statusCode       int
		statusCodeConfig string
		expectedCode     int
	}{
		{
			name:             "map string value",
			statusCode:       429,
			statusCodeConfig: `{"429":"503"}`,
			expectedCode:     503,
		},
		{
			name:             "map int value",
			statusCode:       429,
			statusCodeConfig: `{"429":503}`,
			expectedCode:     503,
		},
		{
			name:             "skip invalid string value",
			statusCode:       429,
			statusCodeConfig: `{"429":"bad-code"}`,
			expectedCode:     429,
		},
		{
			name:             "skip status code 200",
			statusCode:       200,
			statusCodeConfig: `{"200":503}`,
			expectedCode:     200,
		},
	}

	for _, tc := range testCases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			newAPIError := &types.NewAPIError{
				StatusCode: tc.statusCode,
			}
			ResetStatusCode(newAPIError, tc.statusCodeConfig)
			require.Equal(t, tc.expectedCode, newAPIError.StatusCode)
		})
	}
}

func TestRelayErrorHandlerTruncatesInvalidJSONBodyInLog(t *testing.T) {
	withDebugEnabled(t, false)

	body := strings.Repeat("b", common.LocalLogContentLimit+256)
	var logBuffer bytes.Buffer

	common.LogWriterMu.Lock()
	oldWriter := gin.DefaultErrorWriter
	gin.DefaultErrorWriter = &logBuffer
	common.LogWriterMu.Unlock()
	t.Cleanup(func() {
		common.LogWriterMu.Lock()
		gin.DefaultErrorWriter = oldWriter
		common.LogWriterMu.Unlock()
	})

	resp := &http.Response{
		StatusCode: http.StatusInternalServerError,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.Equal(t, "bad response status code 500", newAPIError.Error())
	require.Contains(t, logBuffer.String(), "[truncated")
	require.Contains(t, logBuffer.String(), fmt.Sprintf("original_length=%d", len(body)))
	require.NotContains(t, logBuffer.String(), strings.Repeat("b", common.LocalLogContentLimit+1))
}

func TestRelayErrorHandlerKeepsStructuredErrorMessage(t *testing.T) {
	message := strings.Repeat("c", common.LocalLogContentLimit+256)
	body := `{"message":"` + message + `"}`
	resp := &http.Response{
		StatusCode: http.StatusInternalServerError,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.Equal(t, message, newAPIError.Error())
}

